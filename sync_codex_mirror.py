#!/usr/bin/env python3
"""
Regenerate the OpenAI Codex port of this repo from the canonical Claude Code sources.

  .claude/skills/       -> .agents/skills/       files copied; *.md get path rewrites
  .claude/agents/*.md   -> .codex/agents/*.toml  frontmatter name/description + body
  .claude/CLAUDE.md     -> AGENTS.md             path rewrites + a generated-file header

Only PATHS are rewritten, never the word "Claude". Skill text states facts about Jude's own
tooling ("his personal Claude Code AI", "a dozen Claude sessions") that a blind Claude -> Codex
replace would falsify. The Sep 21 2026 hand port did exactly that, and also pointed every
command at a nonexistent .Codex/skills/. AGENTS.md gets a header telling Codex that "Claude"
in these files means the agent running them.

Anything in CLAUDE.md between `<!-- codex:skip-start -->` and `<!-- codex:skip-end -->` is
dropped from AGENTS.md (the note about this mirror, which reads wrong once its paths are
rewritten).

.codex/config.toml (MCP servers, holds the Make auth header) is never touched.

Dry run by default; --apply writes, and deletes mirror files whose source is gone.
Run from the repo root:  python3 sync_codex_mirror.py [--apply]
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SKILLS_SRC = ROOT / ".claude" / "skills"
SKILLS_DST = ROOT / ".agents" / "skills"
AGENTS_SRC = ROOT / ".claude" / "agents"
AGENTS_DST = ROOT / ".codex" / "agents"
CLAUDE_MD = ROOT / ".claude" / "CLAUDE.md"
AGENTS_MD = ROOT / "AGENTS.md"

PATH_REWRITES = [
    (".claude/skills/", ".agents/skills/"),
    (".claude/agents/", ".codex/agents/"),
]
SKIP_NAMES = {".DS_Store", "__pycache__"}
SKIP_BLOCK_RE = re.compile(r"<!-- codex:skip-start -->.*?<!-- codex:skip-end -->\n?", re.S)

AGENTS_HEADER = """\
<!-- GENERATED by sync_codex_mirror.py from .claude/CLAUDE.md. Do not edit here: edit the
     canonical file and rerun `python3 sync_codex_mirror.py --apply`. -->

> **Codex note:** this file, `.agents/skills/` and `.codex/agents/` are generated from the
> Claude Code originals (`.claude/`), which stay canonical. Wherever these files say "Claude",
> read it as the agent running the skill (you). Mentions of Claude as Jude's own tooling
> are facts about him and stay as written.
"""


def rewrite_paths(text):
    for old, new in PATH_REWRITES:
        text = text.replace(old, new)
    return text


def skipped(path):
    return any(part in SKIP_NAMES for part in path.parts) or path.suffix == ".pyc"


def desired_skills():
    out = {}
    for src in SKILLS_SRC.rglob("*"):
        rel = src.relative_to(SKILLS_SRC)
        if src.is_dir() or skipped(rel):
            continue
        data = src.read_bytes()
        if src.suffix == ".md":
            data = rewrite_paths(data.decode("utf-8")).encode("utf-8")
        out[SKILLS_DST / rel] = data
    return out


def agent_to_toml(md_text, fname):
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", md_text, re.S)
    if not m:
        sys.exit(f"{fname}: no YAML frontmatter")
    meta = dict(
        line.split(":", 1) for line in m.group(1).splitlines() if ":" in line
    )
    meta = {k.strip(): v.strip() for k, v in meta.items()}
    body = rewrite_paths(m.group(2).lstrip("\n"))
    if "'''" in body:
        sys.exit(f"{fname}: body contains ''' and cannot be a TOML literal string")
    return (
        f"name = {json.dumps(meta['name'])}\n"
        f"description = {json.dumps(meta['description'])}\n"
        f"developer_instructions = '''\n{body.rstrip()}\n'''\n"
    ).encode("utf-8")


def desired_agents():
    return {
        AGENTS_DST / (src.stem + ".toml"): agent_to_toml(src.read_text("utf-8"), src.name)
        for src in sorted(AGENTS_SRC.glob("*.md"))
    }


def desired_agents_md():
    text = SKIP_BLOCK_RE.sub("", CLAUDE_MD.read_text("utf-8"))
    text = text.replace("# CLAUDE.md\n", "# AGENTS.md\n\n" + AGENTS_HEADER, 1)
    text = text.replace(
        "This file provides guidance to Claude Code (claude.ai/code)",
        "This file provides guidance to Codex", 1)
    return {AGENTS_MD: rewrite_paths(text).encode("utf-8")}


def existing():
    found = {p for p in SKILLS_DST.rglob("*") if p.is_file()} if SKILLS_DST.exists() else set()
    if AGENTS_DST.exists():
        found |= set(AGENTS_DST.glob("*.toml"))
    if AGENTS_MD.exists():
        found.add(AGENTS_MD)
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--apply", action="store_true", help="write changes (default: dry run)")
    args = ap.parse_args()

    want = {**desired_skills(), **desired_agents(), **desired_agents_md()}
    have = existing()
    add = sorted(p for p in want if p not in have)
    update = sorted(p for p in want if p in have and p.read_bytes() != want[p])
    delete = sorted(p for p in have if p not in want)

    for label, paths in (("add", add), ("update", update), ("delete", delete)):
        for p in paths:
            print(f"{label:6} {p.relative_to(ROOT)}")
    print(f"\n{len(add)} add, {len(update)} update, {len(delete)} delete, "
          f"{len(want) - len(add) - len(update)} unchanged")

    if not args.apply:
        print("Dry run. Rerun with --apply to write.")
        return
    for p in add + update:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(want[p])
        if p.suffix == ".py":
            src = SKILLS_SRC / p.relative_to(SKILLS_DST)
            shutil.copymode(src, p)
    for p in delete:
        p.unlink()
    # prune directories emptied by deletes (deepest first), never the mirror roots themselves
    if SKILLS_DST.exists():
        for d in sorted((d for d in SKILLS_DST.rglob("*") if d.is_dir()), key=lambda d: -len(d.parts)):
            if not any(d.iterdir()):
                d.rmdir()
    print("Applied.")


if __name__ == "__main__":
    main()
